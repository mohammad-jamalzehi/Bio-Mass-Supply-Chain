function Prose({ children }: { children: string }) {
  return <Markdown remarkPlugins={[remarkGfm, remarkMath]} rehypePlugins={[rehypeKatex]} components={{
    table: ({ node: _node, ...props }) => <div className="table-scroll" tabIndex={0} role="region" aria-label="Data table"><table {...props} /></div>,
  }}>{children}</Markdown>
}

function Equation({ item }: { item: typeof equations[number] }) {
  const [feedback, setFeedback] = useState('')
  return <div className="equation" id={`eq-${item.id}`}>
    <div className="equation-top"><a className="equation-number" href={`#eq-${item.id}`}>({item.id})</a><h4>{item.title}</h4>
      <button type="button" onClick={async () => {
        try { await navigator.clipboard.writeText(item.latex); setFeedback('Copied') }
        catch { setFeedback('Select LaTeX below'); }
      }}>Copy LaTeX</button></div>
    <div className="equation-math" tabIndex={0} role="region" aria-label={item.title}><Prose>{'$$\n' + item.latex + '\n$$'}</Prose></div>
    <p>{item.meaning} <a href={implementation(item.source)}>Implementation ↗</a></p>
    <span className="feedback" aria-live="polite">{feedback}</span>
    {feedback === 'Select LaTeX below' && <textarea aria-label="Equation LaTeX" readOnly value={item.latex} onFocus={(event) => event.target.select()} />}
  </div>
}

function Results() {
  return <>
    <div className="callout"><strong>Synthetic verification</strong><p>Costs and dispatch below are generated by the tested Python MILPs. Values are for test fixtures.</p></div>
    <div className="table-scroll" tabIndex={0} role="region" aria-label="Synthetic results"><table><thead><tr><th>Experiment</th><th>Selected fuel</th><th>Day-one closing stock</th><th>Cost / bound</th><th>Termination</th></tr></thead><tbody>
      {results.fixtures.map((fixture) => {
        const first = fixture.days[0]
        const winner = 'inventory_by_fuel' in first && first.inventory_by_fuel ? Object.entries(first.inventory_by_fuel).find(([, entry]) => entry.delivered > 0) : undefined
        const stock = 'inventory_by_fuel' in first ? Object.values(first.inventory_by_fuel).reduce((sum, entry) => sum + entry.closing, 0) : first.inventory.closing
        return <tr key={fixture.scenario}><th>Phase {fixture.phase} · {caseNames[fixture.scenario]}</th><td>{winner ? fuelNames[winner[0]] : 'Single test fuel'}</td>
          <td>{num(stock)} m³</td><td>${num(fixture.totals.cost)} / ${num(fixture.solver.best_cost_bound)}</td>
          <td>Optimal · {num(fixture.solver.mip_gap * 100, 5)}% gap</td></tr>
      })}
    </tbody></table></div>
    <p>Phase 2 checked four truck schedules by hand. Phase 3 exhausted the four day-one choices in each variant. The base pellet plan stores 0.5 m³ on day one and burns it on day two. Lowering the silo cap changes the winning fuel to wood chips. Removing first-day storage changes it to briquettes.</p>
    <p className="source-links"><a href={implementation('tests/test_phase2.py')}>Phase 2 tests ↗</a><a href={implementation('tests/test_phase3.py')}>Phase 3 tests ↗</a></p>
    <details className="annual"><summary>Phase 4 · Provisional historical-input runs</summary>
      <p>The following archived annual runs reached a 30-second solver limit and passed the dispatch audit. Their numerical inputs, emissions accuracy and global optimality remain unverified.</p>
      <div className="table-scroll" tabIndex={0} role="region" aria-label="Annual run diagnostics"><table><thead><tr><th>Scenario</th><th>Incumbent</th><th>Best bound</th><th>MIP gap</th></tr></thead><tbody>
        {results.annual.filter((row) => row.days_requested === 365).map((row) => <tr key={row.scenario_id}>
          <th>{caseNames[row.scenario_id]}</th><td>{num(row.solver.solver_reported_objective)}</td><td>{num(row.solver.best_bound)}</td><td>{num(row.solver.mip_gap * 100, 5)}%</td></tr>)}
      </tbody></table></div>
      <p><a href={implementation('docs/phase-4-annual.md')}>Reconciliation and run records ↗</a></p>
    </details>
  </>
}

